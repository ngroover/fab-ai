/// Which deck card enum a player's `DeckCardId`s refer to. `Player` is shared
/// by both heroes, so this is how untyped engine code turns a `Card` into the
/// right deck's id and back.
/// Every token a player can create during play, whatever their deck. Tokens
/// are in no decklist, so they get an id space of their own rather than a
/// place in the deck enums: a token's `DeckCardId` is its field in
/// `Player::tokens`, and means nothing in any other `CardCounts`.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash, PartialOrd, Ord)]
#[repr(u8)]
pub enum TokenCard {
    QuickenToken,
}

impl TokenCard {
    pub const ALL: &'static [TokenCard] = &[TokenCard::QuickenToken];
    pub const COUNT: usize = Self::ALL.len();

    /// This token's field position in `Player::tokens`.
    #[inline]
    pub const fn id(self) -> DeckCardId {
        DeckCardId::new(self as usize)
    }

    /// The token whose id is `id`. Panics if `id` is past the end.
    #[inline]
    pub const fn from_id(id: DeckCardId) -> Self {
        Self::ALL[id.get()]
    }

    /// The game-wide `Card` this token stands for, for its catalog data.
    #[inline]
    pub const fn card(self) -> Card {
        match self {
            TokenCard::QuickenToken => Card::QuickenToken,
        }
    }
}

const _: () = assert!(TokenCard::COUNT <= MAX_DECK_IDS, "TokenCard has more tokens than a CardCounts can hold");

#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
#[repr(u8)]
pub enum DeckKind {
    Rhinar,
    Dorinthea,
}

impl DeckKind {
    /// The deck a hero plays. Panics for a card that is not a supported hero.
    pub const fn for_hero(hero: Card) -> Self {
        match hero {
            Card::Rhinar => DeckKind::Rhinar,
            Card::Dorinthea => DeckKind::Dorinthea,
            _ => panic!("no deck card enum for this hero"),
        }
    }

    /// `card`'s id in this deck, or `None` if the deck does not contain it.
    #[inline]
    pub const fn id_of(self, card: Card) -> Option<DeckCardId> {
        match self {
            DeckKind::Rhinar => match RhinarCard::from_card(card) {
                Some(c) => Some(c.id()),
                None => None,
            },
            DeckKind::Dorinthea => match DorintheaCard::from_card(card) {
                Some(c) => Some(c.id()),
                None => None,
            },
        }
    }

    /// The `Card` with id `id` in this deck. Panics if `id` is past the end of
    /// the deck.
    #[inline]
    pub const fn card(self, id: DeckCardId) -> Card {
        match self {
            DeckKind::Rhinar => RhinarCard::ALL[id.get()].card(),
            DeckKind::Dorinthea => DorintheaCard::ALL[id.get()].card(),
        }
    }

    /// How many distinct cards the deck has.
    pub const fn count(self) -> usize {
        match self {
            DeckKind::Rhinar => RhinarCard::COUNT,
            DeckKind::Dorinthea => DorintheaCard::COUNT,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cards::CardType;
    use crate::decks::{build_dorinthea_deck, build_rhinar_deck};
    use std::collections::BTreeSet;

    /// The distinct cards in a decklist a player owns: everything except the
    /// hero.
    fn owned(deck: [Card; 46]) -> BTreeSet<u8> {
        deck.into_iter()
            .filter(|c| !matches!(c.data().typ, CardType::Hero))
            .map(|c| c as u8)
            .collect()
    }

    fn enum_cards<D: DeckCard>() -> BTreeSet<u8> {
        D::ALL.iter().map(|c| c.card() as u8).collect()
    }

    #[test]
    fn rhinar_enum_matches_decklist() {
        assert_eq!(enum_cards::<RhinarCard>(), owned(build_rhinar_deck()));
    }

    #[test]
    fn dorinthea_enum_matches_decklist() {
        assert_eq!(enum_cards::<DorintheaCard>(), owned(build_dorinthea_deck()));
    }

    fn round_trips<D: DeckCard>() {
        for (i, &c) in D::ALL.iter().enumerate() {
            assert_eq!(c.id().get(), i);
            assert_eq!(D::from_card(c.card()), Some(c));
            assert_eq!(D::from_id(c.id()), c);
            assert_eq!(D::KIND.id_of(c.card()), Some(c.id()));
            assert_eq!(D::KIND.card(c.id()), c.card());
        }
        assert_eq!(D::KIND.count(), D::COUNT);
    }

    #[test]
    fn ids_round_trip() {
        round_trips::<RhinarCard>();
        round_trips::<DorintheaCard>();
    }

    #[test]
    fn cards_outside_the_deck_have_no_id() {
        assert_eq!(RhinarCard::from_card(Card::ThrustR), None);
        assert_eq!(DorintheaCard::from_card(Card::BareFangsR), None);
        assert_eq!(RhinarCard::from_card(Card::Dawnblade), None);
        assert_eq!(DorintheaCard::from_card(Card::IronhideLegs), None);
        // A hero is never in a zone a `CardCounts` tracks, so it has no id.
        assert_eq!(RhinarCard::from_card(Card::Rhinar), None);
        // Shared cards get each deck's own id.
        assert_eq!(RhinarCard::TitaniumBaubleB.id().get(), 18);
        assert_eq!(DorintheaCard::TitaniumBaubleB.id().get(), 17);
        assert_eq!(RhinarCard::BlossomOfSpring.id().get(), 22);
        assert_eq!(DorintheaCard::BlossomOfSpring.id().get(), 23);
    }

    #[test]
    fn weapon_and_equipment_come_after_the_playable_deck() {
        // The playable cards keep the low ids, so the weapon and equipment
        // only ever add fields past them.
        fn check<D: DeckCard>() {
            for &c in D::ALL {
                let is_gear = matches!(c.card().data().typ, CardType::Weapon | CardType::Equipment);
                assert_eq!(is_gear, c.id().get() >= 21, "{:?}", c);
            }
        }
        check::<RhinarCard>();
        check::<DorintheaCard>();
    }

    #[test]
    fn heroes_map_to_their_decks() {
        assert_eq!(DeckKind::for_hero(Card::Rhinar), DeckKind::Rhinar);
        assert_eq!(DeckKind::for_hero(Card::Dorinthea), DeckKind::Dorinthea);
    }
}
