//! Per-deck card enums: for each decklist, a compile-time enum holding every
//! card that player owns apart from the hero — the playable deck first, then
//! the weapon and equipment. The weapon and equipment never reach the hand,
//! but worn equipment sits in an equipment zone and can be destroyed into the
//! graveyard, so the unordered zones that hold them need ids for them too.
//!
//! `Card` lists every card in the game. A given player only ever owns a
//! small subset of those, so each deck gets its own enum (`RhinarCard`,
//! `DorintheaCard`) whose variants are numbered densely from 0. That number is
//! the card's `DeckCardId`, which is its field position in a `CardCounts`
//! bitfield (see `card_counts`). A deck's whole hand therefore packs into one
//! `u64` with no lookup table built at runtime, and so does each of the
//! player's other unordered zones (pitch, graveyard, banish, equipment).
//!
//! The enums are generated by `deck_cards!`, which also checks at compile time
//! that the deck fits in a `CardCounts`. `Player` is not generic over its deck,
//! so the engine reaches the right enum through a `DeckKind` stored on the
//! player. Code that knows which deck it holds uses the typed enum directly
//! (`player.hand_count(RhinarCard::BareFangsR)`).

use crate::card_counts::{DeckCardId, MAX_DECK_IDS};
use crate::cards::Card;

/// A card enum generated for one decklist by `deck_cards!`.
///
/// Every variant shares its name with the `Card` it stands for, and the
/// variants are numbered `0..COUNT` in declaration order.
pub trait DeckCard: Copy + Eq + std::fmt::Debug + 'static {
    /// The deck this enum belongs to.
    const KIND: DeckKind;
    /// How many distinct cards the deck has.
    const COUNT: usize;
    /// Every variant, indexed by its `DeckCardId`.
    const ALL: &'static [Self];

    /// This card's field position in a `CardCounts`.
    fn id(self) -> DeckCardId;
    /// The game-wide `Card` this variant stands for.
    fn card(self) -> Card;
    /// The variant for `card`, or `None` if `card` is not in this deck.
    fn from_card(card: Card) -> Option<Self>;

    /// The variant whose id is `id`. Panics if `id` is past the end of the
    /// deck.
    #[inline]
    fn from_id(id: DeckCardId) -> Self {
        Self::ALL[id.get()]
    }
}

/// Generate a deck card enum, its `DeckCard` impl, and a compile-time check
/// that the deck fits in a `CardCounts`. Each variant must name a `Card`
/// variant.
macro_rules! deck_cards {
    (
        $(#[$meta:meta])*
        $vis:vis enum $name:ident for $kind:ident { $($variant:ident),+ $(,)? }
    ) => {
        $(#[$meta])*
        #[derive(Clone, Copy, PartialEq, Eq, Debug, Hash, PartialOrd, Ord)]
        #[repr(u8)]
        $vis enum $name {
            $($variant),+
        }

        impl $name {
            pub const ALL: &'static [$name] = &[$($name::$variant),+];
            pub const COUNT: usize = Self::ALL.len();

            #[inline]
            pub const fn id(self) -> DeckCardId {
                DeckCardId::new(self as usize)
            }

            #[inline]
            pub const fn card(self) -> Card {
                match self {
                    $($name::$variant => Card::$variant),+
                }
            }

            #[inline]
            pub const fn from_card(card: Card) -> Option<Self> {
                match card {
                    $(Card::$variant => Some($name::$variant),)+
                    _ => None,
                }
            }
        }

        const _: () = assert!(
            $name::COUNT <= MAX_DECK_IDS,
            concat!(stringify!($name), " has more cards than a CardCounts can hold"),
        );

        impl DeckCard for $name {
            const KIND: DeckKind = DeckKind::$kind;
            const COUNT: usize = $name::COUNT;
            const ALL: &'static [Self] = $name::ALL;

            #[inline]
            fn id(self) -> DeckCardId {
                $name::id(self)
            }

            #[inline]
            fn card(self) -> Card {
                $name::card(self)
            }

            #[inline]
            fn from_card(card: Card) -> Option<Self> {
                $name::from_card(card)
            }
        }
    };
}

